const crypto = require("crypto");

const POLICY_CODE = "cargocamp_simple_signature";
const POLICY_VERSION = "0.1";
const JURISDICTION = "RU";

const POLICY_TEXT = `
ПРАВИЛА ИСПОЛЬЗОВАНИЯ ПРОСТОЙ ЭЛЕКТРОННОЙ ПОДПИСИ CARGOCAMP

Редакция ${POLICY_VERSION} — проект для согласования

1. Общие положения

Настоящие правила описывают предполагаемый порядок
подтверждения электронных документов пользователями
информационной системы CargoCamp.

Правила применяются к документам, для которых
система явно предоставляет процедуру электронной
подписи. Простое использование приложения,
создание заказа или подтверждение выполнения
работы сами по себе не считаются подписанием
отдельного документа.

2. Идентификация пользователя

В предполагаемой процедуре подписания используются
учётная запись пользователя, подтверждённый номер
телефона, действующая проверка личности и
одноразовый код, направляемый системой на
соответствующий номер телефона.

Система должна фиксировать пользователя,
документ и способ подтверждения.

3. Подписание конкретного документа

Перед подписанием пользователю предоставляется
возможность ознакомиться с документом.

Одноразовый код предназначается для подтверждения
конкретного документа и конкретной его версии.

Система должна фиксировать идентификатор документа,
его контрольную сумму SHA-256, пользователя, дату
подтверждения и результат проверки кода.

Подтверждение одного документа не означает
автоматического согласия с другими документами.

4. Конфиденциальность

Пользователь обязуется не передавать третьим лицам
коды подтверждения и иные средства доступа к своей
учётной записи.

При подозрении на компрометацию доступа пользователь
должен незамедлительно обратиться в поддержку
CargoCamp.

5. Подтверждение обеих сторон

Для двустороннего договора подтверждение одной
стороны не означает подписание документа другой
стороной.

Статус полностью подписанного документа может
устанавливаться только после выполнения процедуры
подписания каждой стороной.

6. Хранение и проверка

CargoCamp должен сохранять сведения о документе,
его версии, контрольной сумме и действиях сторон,
необходимые для последующей проверки.

При изменении содержания документа должна
формироваться новая версия, требующая отдельного
подтверждения.

7. Ограничения

Простая электронная подпись может применяться
только в случаях, допускаемых законодательством
и соглашением участников электронного взаимодействия.

Окончательные условия юридического признания
подписанных документов, круг участников соглашения,
порядок оспаривания и иные существенные положения
подлежат отдельному согласованию.

Конец проекта правил.
`.trim();

const POLICY_SHA256 = crypto
    .createHash("sha256")
    .update(POLICY_TEXT, "utf8")
    .digest("hex");

const POLICY_ENABLED =
    POLICY_VERSION !== "0.1" &&
    process.env.CARGOCAMP_SIGNATURE_AGREEMENT_ENABLED ===
    "true";

function getSignaturePolicy() {
    return {
        code: POLICY_CODE,
        version: POLICY_VERSION,
        jurisdiction: JURISDICTION,
        sha256: POLICY_SHA256,
        text: POLICY_TEXT,
        enabled: POLICY_ENABLED,
    };
}

module.exports = {
    getSignaturePolicy,
};
