const POLICY_SHA256 = crypto
    .createHash("sha256")
    .update(POLICY_TEXT, "utf8")
    .digest("hex");

const POLICY_ENABLED =
    POLICY_VERSION === "1.1" &&
    process.env.CARGOCAMP_SIGNATURE_AGREEMENT_ENABLED ===
    "true";

function getSignaturePolicy() {
    return {
        code: POLICY_CODE,
        version: POLICY_VERSION,
        jurisdiction: JURISDICTION,
        sha256: POLICY_SHA256,
        text: POLICY_TEXT,
        enabled: POLICY_ENABLED,
    };
}

